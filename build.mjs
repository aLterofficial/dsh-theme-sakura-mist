/**
 * 樱雾 · Sakura Mist —— client bundle 构建脚本
 *
 * DSH 的浏览器插件由宿主直接从包里读取 lib/client.js 并下发，因此它必须是
 * 自注册的经典脚本（不能是 ESM）：window.__ModuleLoader__.load({ id, factory })。
 * 这里把 src/theme.css 与 src/client-entry.js 合成这一个文件，避免任何构建依赖。
 *
 * 用法：node build.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const css = readFileSync(join(root, 'src', 'theme.css'), 'utf8')
const entry = readFileSync(join(root, 'src', 'client-entry.js'), 'utf8')

const indent = (text) => text.replace(/^/gm, '    ')

const bundle = `/*! 樱雾 · Sakura Mist v${pkg.version} — generated by build.mjs; edit src/ instead. */
window.__ModuleLoader__.load({
    id: ${JSON.stringify(pkg.name)},
    factory: (require) => {
        var module = { exports: {} };
        var exports = module.exports;
        Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

        const __SAKURA_VERSION__ = ${JSON.stringify(pkg.version)};
        const __SAKURA_CSS__ = ${JSON.stringify(css)};

${indent(entry)}

        exports.name = "sakura-mist-theme";
        exports.apply = apply;
        exports.disposeStyles = disposeStyles;
        return module.exports;
    }
});

//# sourceURL=dsh-theme-sakura-mist/client.js
`

writeFileSync(join(root, 'lib', 'client.js'), bundle, 'utf8')
console.log(`built lib/client.js (${bundle.length} bytes, css ${css.length} bytes)`)
